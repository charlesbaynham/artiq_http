const INFINITE_REPEATS = 2147483647;
const MAX_DEMO_POINTS = 4000;
const POINTS_PER_TICK_TARGET_TICKS = 40;
const RUN_CLEANUP_DELAY_MS = 4000;
const PLAIN_RUN_DURATION_MS = 4000;
// Mirrors mock_backend.py's _SUBMIT_PENDING_DELAY_S: a submission sits
// `pending` for this long before flipping to `running` and starting to
// stream data, so both mocks show the same realistic queue -> live lifecycle
// instead of a run appearing "running" the instant it's submitted.
const SUBMIT_PENDING_DELAY_MS = 2000;

const GENERIC_SCAN_CHANNELS = {
  signal: {
    path: "signal",
    description: "Excitation",
    type: "float",
    scale: 1.0,
    unit: "",
  },
  reference: {
    path: "reference",
    description: "Reference",
    type: "float",
    scale: 1.0,
    unit: "",
    display_hints: { priority: -1 },
  },
  atom_number: {
    path: "atom_number",
    description: "Atom number",
    type: "float",
    scale: 1.0,
    unit: "",
  },
};

function allocateRid() {
  const rid = state.nextRid;
  state.nextRid += 1;
  return rid;
}

function normaliseExpId(body) {
  if (
    !body ||
    typeof body.file !== "string" ||
    typeof body.class_name !== "string"
  ) {
    throw new MockApiError(
      422,
      "Invalid ExpID: 'file' and 'class_name' are required",
    );
  }
  return {
    log_level: Number.isFinite(body.log_level) ? body.log_level : 30,
    file: body.file,
    class_name: body.class_name,
    arguments: body.arguments == null ? {} : body.arguments,
    repo_rev: body.repo_rev ?? null,
  };
}

function deriveFragmentFqn(file, className) {
  const modulePath = file.replace(/\.py$/, "").replaceAll("/", ".");
  return `${modulePath}.${className}`;
}

function axisPointValues(axisWire) {
  const { type, range } = axisWire;
  if (type === "list") return (range.values || []).slice();
  if (type === "linear")
    return linspace(range.start, range.stop, range.num_points);
  if (type === "centre_span") {
    return linspace(
      range.centre - range.half_span,
      range.centre + range.half_span,
      range.num_points,
    );
  }
  return [0];
}

function axisDescriptorForDataset(axisWire, arginfo, values) {
  const min = Math.min(...values);
  const max = Math.max(...values);
  const increment = values.length > 1 ? (max - min) / (values.length - 1) : 0;
  const schema = extractSchemataFromArginfo(arginfo)[axisWire.fqn];
  const param = schema
    ? { ...schema, unit: schema.spec?.unit ?? "" }
    : {
        default: "0",
        description: axisWire.fqn,
        fqn: axisWire.fqn,
        unit: "",
        type: "float",
        spec: { is_scannable: true, scale: 1 },
      };
  if (!param.fqn) param.fqn = axisWire.fqn;
  return { increment, max, min, path: axisWire.path ?? "*", param };
}

function cartesianProduct(valueArrays) {
  return valueArrays.reduce(
    (acc, values) => {
      const out = [];
      for (const prefixPt of acc)
        for (const v of values) out.push([...prefixPt, v]);
      return out;
    },
    [[]],
  );
}

function buildShuffledPlan(grid, repeats) {
  const plan = [];
  for (let r = 0; r < repeats; r++) for (const pt of grid) plan.push(pt);
  return shuffle(plan);
}

function sampleChannelsGeneric(pt, center, axisSpans) {
  let distSq = 0;
  for (let i = 0; i < pt.length; i++) {
    const [lo, hi] = axisSpans[i];
    const span = hi - lo || 1;
    const norm = (pt[i] - center[i]) / (span * 0.25);
    distSq += norm * norm;
  }
  const bump = 1 / (1 + distSq);
  return {
    signal: 0.12 + 0.8 * bump + gauss(0, 0.05),
    reference: 0.5 + gauss(0, 0.03),
    atom_number: Math.max(0, 50000 + 30000 * bump + gauss(0, 3000)),
  };
}

function beginZeroAxisRun(rid, prefix, fragmentFqn) {
  // No scanned axes: a real ndscan 0D run measures once and completes
  // immediately (NoAxisRunner in ndscan/experiment/entry_point.py), so this
  // publishes one point and completes rather than ticking forever like the
  // always-live 0D repeat demo (ndscan.rid_1) does.
  setDataset(`${prefix}.axes`, "[]");
  setDataset(`${prefix}.channels`, JSON.stringify(GENERIC_SCAN_CHANNELS));
  setDataset(`${prefix}.fragment_fqn`, fragmentFqn);
  setDataset(`${prefix}.point.signal`, 0.5 + gauss(0, 0.05));
  setDataset(`${prefix}.point.reference`, 0.5 + gauss(0, 0.03));
  setDataset(
    `${prefix}.point.atom_number`,
    Math.max(0, 50000 + gauss(0, 3000)),
  );
  setDataset(`${prefix}.completed`, true);
  finishRun(rid, prefix);
}

function beginNdscanRun(rid, expid, axesWire, numRepeatsRaw, arginfo) {
  const prefix = `ndscan.rid_${rid}`;
  const fragmentFqn = deriveFragmentFqn(expid.file, expid.class_name);

  if (!axesWire || axesWire.length === 0) {
    beginZeroAxisRun(rid, prefix, fragmentFqn);
    return;
  }

  const valueArrays = axesWire.map(axisPointValues);
  const descriptors = axesWire.map((ax, i) =>
    axisDescriptorForDataset(ax, arginfo, valueArrays[i]),
  );
  setDataset(`${prefix}.axes`, JSON.stringify(descriptors));
  setDataset(`${prefix}.channels`, JSON.stringify(GENERIC_SCAN_CHANNELS));
  setDataset(`${prefix}.fragment_fqn`, fragmentFqn);
  setDataset(`${prefix}.completed`, false);
  for (let i = 0; i < axesWire.length; i++)
    setDataset(`${prefix}.points.axis_${i}`, []);
  for (const key of Object.keys(GENERIC_SCAN_CHANNELS))
    setDataset(`${prefix}.points.channel_${key}`, []);

  const grid = cartesianProduct(valueArrays);
  const gridSize = grid.length;
  const numRepeats = Number.isFinite(numRepeatsRaw) ? numRepeatsRaw : 1;
  const isInfinite =
    numRepeats === INFINITE_REPEATS || !Number.isFinite(numRepeats);
  const finiteTotal = isInfinite ? null : gridSize * Math.max(1, numRepeats);
  const loopForever =
    isInfinite || gridSize === 0 || finiteTotal > MAX_DEMO_POINTS;

  const center = valueArrays.map(
    (vals) => vals[Math.floor(vals.length * 0.4)] ?? vals[0] ?? 0,
  );
  const run = {
    rid,
    prefix,
    numAxes: axesWire.length,
    grid,
    center,
    axisSpans: valueArrays.map((vals) => [
      Math.min(...vals),
      Math.max(...vals),
    ]),
    loopForever,
    plan: buildShuffledPlan(grid, loopForever ? 1 : Math.max(1, numRepeats)),
    idx: 0,
    done: false,
  };
  run.pointsPerTick = Math.max(
    1,
    Math.ceil(run.plan.length / POINTS_PER_TICK_TARGET_TICKS),
  );
  activeRuns.set(rid, run);
}

function appendPoint(run, pt) {
  for (let i = 0; i < run.numAxes; i++) {
    const arr = (
      state.datasets[`${run.prefix}.points.axis_${i}`]?.[1] ?? []
    ).slice();
    arr.push(pt[i]);
    setDataset(`${run.prefix}.points.axis_${i}`, arr);
  }
  const sample = sampleChannelsGeneric(pt, run.center, run.axisSpans);
  for (const [key, value] of Object.entries(sample)) {
    const arr = (
      state.datasets[`${run.prefix}.points.channel_${key}`]?.[1] ?? []
    ).slice();
    arr.push(value);
    setDataset(`${run.prefix}.points.channel_${key}`, arr);
  }
}

function resetRunPoints(run) {
  for (let i = 0; i < run.numAxes; i++)
    setDataset(`${run.prefix}.points.axis_${i}`, []);
  for (const key of Object.keys(GENERIC_SCAN_CHANNELS))
    setDataset(`${run.prefix}.points.channel_${key}`, []);
}

function nudgeCenter(run) {
  run.center = run.center.map((c, i) => {
    const [lo, hi] = run.axisSpans[i];
    const span = hi - lo || 1;
    return Math.max(
      lo,
      Math.min(hi, c + (Math.random() * 2 - 1) * span * 0.15),
    );
  });
}

// Marks *rid*'s dataset completed and its schedule item `run_done`, then
// removes it from the schedule after a short delay — mirroring a real ARTIQ
// master dropping a finished run off the queue. Shared by ndscan run
// completion (completeRun) and the one-shot zero-axis path (beginZeroAxisRun).
function finishRun(rid, prefix) {
  activeRuns.delete(rid);
  setDataset(`${prefix}.completed`, true);
  const item = state.schedule[rid];
  if (item) item.status = "run_done";
  const t = setTimeout(() => {
    pendingCleanupTimeouts.delete(rid);
    delete state.schedule[rid];
  }, RUN_CLEANUP_DELAY_MS);
  pendingCleanupTimeouts.set(rid, t);
}

function completeRun(run) {
  run.done = true;
  finishRun(run.rid, run.prefix);
}

function tickNdscanRun(run) {
  if (run.done) return;
  let remaining = run.pointsPerTick;
  while (remaining > 0) {
    if (run.idx >= run.plan.length) {
      if (run.loopForever) {
        run.plan = buildShuffledPlan(run.grid, 1);
        run.idx = 0;
        nudgeCenter(run);
        resetRunPoints(run);
      } else {
        completeRun(run);
        return;
      }
    }
    if (run.idx >= run.plan.length) return; // defensive: empty grid
    appendPoint(run, run.plan[run.idx++]);
    remaining--;
  }
}

function startRunFromExpid(rid, expid) {
  const [raw] = getNdscanJson(expid.arguments || {});
  if (typeof raw !== "string") {
    // Plain (non-ndscan) experiment: nothing to stream. Simulate a quick job
    // rather than leaving a "running" item stuck forever with no live data.
    const t = setTimeout(() => {
      pendingPlainCompletions.delete(rid);
      delete state.schedule[rid];
    }, PLAIN_RUN_DURATION_MS);
    pendingPlainCompletions.set(rid, t);
    return;
  }
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return;
  }
  const axes = parsed?.scan?.axes ?? [];
  const numRepeats = parsed?.scan?.num_repeats ?? 1;
  const arginfo = findExplistArginfoSync(expid.file, expid.class_name);
  beginNdscanRun(rid, expid, axes, numRepeats, arginfo);
}

function insertScheduleItem(rid, item) {
  state.schedule[rid] = item;
}

// Mirrors mock_backend.py's _activate_submission: after the pending delay,
// flip *rid* to `running` and start its data (unless it was cancelled, or
// its status was otherwise changed, in the meantime).
function scheduleActivation(rid) {
  const t = setTimeout(() => {
    pendingActivationTimeouts.delete(rid);
    const item = state.schedule[rid];
    if (!item || item.status !== "pending") return;
    item.status = "running";
    startRunFromExpid(rid, item.expid);
  }, SUBMIT_PENDING_DELAY_MS);
  pendingActivationTimeouts.set(rid, t);
}

function mockWaitForCompletion(rid, timeoutSeconds) {
  // The mock has no real notion of "finished" on a fixed timeline, so this
  // resolves after a short bounded delay rather than genuinely waiting up to
  // `timeoutSeconds` — good enough to exercise the wait_for_completion=True
  // code path without hanging a demo page.
  const waitMs = Math.min(3000, Math.max(500, timeoutSeconds * 1000));
  return new Promise((resolve) => {
    setTimeout(
      () =>
        resolve({ rid, status: "completed", timed_out: false, error: null }),
      waitMs,
    );
  });
}

function handleSubmitExperiment(url, body) {
  const pipeline = url.searchParams.get("pipeline") ?? "main";
  const priority = Number(url.searchParams.get("priority") ?? "0");
  const flush = (url.searchParams.get("flush") ?? "false") === "true";
  const dueDateRaw = url.searchParams.get("due_date");
  const dueDate =
    dueDateRaw != null && dueDateRaw !== "" ? Number(dueDateRaw) : null;
  const waitForCompletion =
    (url.searchParams.get("wait_for_completion") ?? "false") === "true";
  const timeout = Number(url.searchParams.get("timeout") ?? "600");

  const expid = normaliseExpId(body);
  if (expid.arguments && "ndscan_params" in expid.arguments) {
    const arginfo = findExplistArginfoSync(expid.file, expid.class_name);
    const err = validateNdscanParamsArguments(expid.arguments, arginfo);
    if (err) throw new MockApiError(422, err);
  }

  const rid = allocateRid();
  insertScheduleItem(rid, {
    pipeline,
    priority,
    due_date: dueDate,
    flush,
    status: "pending",
    repo_msg: null,
    expid,
  });
  scheduleActivation(rid);

  if (waitForCompletion) return mockWaitForCompletion(rid, timeout);
  return rid;
}

function handleSubmitScan(url, body) {
  const waitForCompletion =
    (url.searchParams.get("wait_for_completion") ?? "false") === "true";
  const timeout = Number(url.searchParams.get("timeout") ?? "600");

  if (
    !body ||
    typeof body.file !== "string" ||
    typeof body.class_name !== "string" ||
    !Array.isArray(body.axes)
  ) {
    throw new MockApiError(
      422,
      "Invalid ScanSubmitRequest: 'file', 'class_name', and 'axes' are required",
    );
  }
  const { file, class_name: className } = body;
  const arginfo = findExplistArginfoSync(file, className);
  if (!arginfo)
    throw new MockApiError(
      404,
      `Experiment ${file}/${className} not found in explist`,
    );

  const ndscanParams = buildNdscanParamsFromArginfo(
    arginfo,
    file,
    className,
    body.axes,
    body.fixed_params,
    body.num_repeats ?? 1,
  );

  const argumentsObj = { ndscan_params: ndscanParams };
  const err = validateNdscanParamsArguments(argumentsObj, arginfo);
  if (err) throw new MockApiError(422, err);

  const expid = {
    log_level: 30,
    file,
    class_name: className,
    arguments: argumentsObj,
    repo_rev: body.repo_rev ?? null,
  };
  const rid = allocateRid();
  insertScheduleItem(rid, {
    pipeline: body.pipeline ?? "main",
    priority: body.priority ?? 0,
    due_date: body.due_date ?? null,
    flush: !!body.flush,
    status: "pending",
    repo_msg: null,
    expid,
  });
  scheduleActivation(rid);

  if (waitForCompletion) return mockWaitForCompletion(rid, timeout);
  return rid;
}

function handleCancel(url) {
  const rid = Number(url.searchParams.get("rid"));
  if (!Number.isFinite(rid) || !(rid in state.schedule)) {
    throw new MockApiError(404, `RID ${rid} not found in schedule`);
  }
  delete state.schedule[rid];

  const run = activeRuns.get(rid);
  if (run) {
    run.done = true;
    activeRuns.delete(rid);
    setDataset(`${run.prefix}.completed`, true);
  }
  const activationT = pendingActivationTimeouts.get(rid);
  if (activationT) {
    clearTimeout(activationT);
    pendingActivationTimeouts.delete(rid);
  }
  const cleanupT = pendingCleanupTimeouts.get(rid);
  if (cleanupT) {
    clearTimeout(cleanupT);
    pendingCleanupTimeouts.delete(rid);
  }
  const plainT = pendingPlainCompletions.get(rid);
  if (plainT) {
    clearTimeout(plainT);
    pendingPlainCompletions.delete(rid);
  }
  return null;
}

// ── Logs / health ──────────────────────────────────────────────────────────

function handleGetLogs(url) {
  const sourceRegex = url.searchParams.get("source_regex");
  const messageRegex = url.searchParams.get("message_regex");
  const minLevel = url.searchParams.get("min_level");
  const maxLevel = url.searchParams.get("max_level");
  const since = url.searchParams.get("since");
  const until = url.searchParams.get("until");
  const limit = url.searchParams.get("limit");

  let sourceRe = null;
  let messageRe = null;
  try {
    if (sourceRegex) sourceRe = new RegExp(sourceRegex);
  } catch (e) {
    throw new MockApiError(400, `Invalid regex for source_regex: ${e.message}`);
  }
  try {
    if (messageRegex) messageRe = new RegExp(messageRegex);
  } catch (e) {
    throw new MockApiError(
      400,
      `Invalid regex for message_regex: ${e.message}`,
    );
  }

  let entries = state.logs.filter((e) => {
    if (minLevel != null && (e.level ?? -Infinity) < Number(minLevel))
      return false;
    if (maxLevel != null && (e.level ?? Infinity) > Number(maxLevel))
      return false;
    if (since != null && (e.timestamp ?? Infinity) < Number(since))
      return false;
    if (until != null && (e.timestamp ?? -Infinity) > Number(until))
      return false;
    if (sourceRe && !sourceRe.test(String(e.source ?? ""))) return false;
    if (messageRe && !messageRe.test(String(e.message ?? ""))) return false;
    return true;
  });
  if (limit != null) entries = entries.slice(0, Number(limit));
  return { logs: entries };
}

// ── Route table ──────────────────────────────────────────────────────────────

async function routeApi(method, url, body) {
  await ensureLoaded();
  const segs = url.pathname.split("/").filter(Boolean);
  if (segs[0] !== "api") throw new MockApiError(404, "Not Found");
  const rest = segs.slice(1);

  if (rest.length === 0) {
    if (method === "GET") return { message: "Hello World" };
    throw new MockApiError(405, "Method Not Allowed");
  }

  if (rest[0] === "explist") {
    if (rest.length === 1) {
      if (method === "GET") return handleGetExplist(url);
      throw new MockApiError(405, "Method Not Allowed");
    }
    if (rest[1] === "search") {
      if (method === "GET") return handleSearchExplist(url);
      throw new MockApiError(405, "Method Not Allowed");
    }
    if (rest.length >= 4) {
      const suffix = rest[rest.length - 1];
      const className = decodeURIComponent(rest[rest.length - 2]);
      const file = rest
        .slice(1, rest.length - 2)
        .map(decodeURIComponent)
        .join("/");
      if (suffix === "arginfo" && method === "GET")
        return handleGetArginfo(file, className);
      if (suffix === "defaults" && method === "GET")
        return handleDefaults(file, className);
      if (suffix === "recompute" && method === "POST")
        return handleGetArginfo(file, className);
    }
    throw new MockApiError(404, "Not Found");
  }

  if (rest[0] === "schedule") {
    if (rest.length === 1) {
      if (method === "GET") return { ...state.schedule };
      if (method === "POST") return handleSubmitExperiment(url, body);
      throw new MockApiError(405, "Method Not Allowed");
    }
    if (rest.length === 2 && method === "GET") {
      const rid = Number(rest[1]);
      if (!(rid in state.schedule))
        throw new MockApiError(404, `RID ${rid} not found in schedule`);
      return state.schedule[rid];
    }
    throw new MockApiError(404, "Not Found");
  }

  if (rest[0] === "scan") {
    // client.js posts to "api/scan/submit-and-wait" when wait_for_completion is
    // true, but the real backend only ever exposes POST /api/scan with a
    // wait_for_completion query param — there is no such route in api.py. We
    // support both paths defensively so the demo works regardless of that
    // pre-existing client.js/api.py mismatch (not something this package owns).
    if (rest.length === 1 && method === "POST")
      return handleSubmitScan(url, body);
    if (
      rest.length === 2 &&
      rest[1] === "submit-and-wait" &&
      method === "POST"
    ) {
      const forced = new URL(url);
      forced.searchParams.set("wait_for_completion", "true");
      return handleSubmitScan(forced, body);
    }
    throw new MockApiError(404, "Not Found");
  }

  if (rest[0] === "cancel" && rest.length === 1) {
    if (method === "POST") return handleCancel(url);
    throw new MockApiError(405, "Method Not Allowed");
  }

  if (rest[0] === "datasets") {
    if (rest.length === 1 && method === "GET") return { ...state.datasets };
    if (rest.length === 2 && rest[1] === "names" && method === "GET") {
      return { names: Object.keys(state.datasets) };
    }
    if (rest.length === 2 && rest[1] === "values" && method === "GET") {
      const names = (url.searchParams.get("names") ?? "")
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean);
      const out = {};
      for (const n of names)
        if (n in state.datasets) out[n] = state.datasets[n];
      return out;
    }
    throw new MockApiError(404, "Not Found");
  }

  if (rest[0] === "logs" && rest.length === 1) {
    if (method === "GET") return handleGetLogs(url);
    throw new MockApiError(405, "Method Not Allowed");
  }

  if (rest[0] === "health" && rest.length === 1) {
    if (method === "GET") return state.health;
    throw new MockApiError(405, "Method Not Allowed");
  }

  throw new MockApiError(404, "Not Found");
}

// ── fetch patch ──────────────────────────────────────────────────────────────

async function extractBody(input, init) {
  if (init && init.body != null) {
    if (typeof init.body === "string") {
      try {
        return JSON.parse(init.body);
      } catch {
        return null;
      }
    }
    return init.body;
  }
  if (
    typeof Request !== "undefined" &&
    input instanceof Request &&
    input.body
  ) {
    try {
      return await input.clone().json();
    } catch {
      return null;
    }
  }
  return null;
}

function isMockApiUrl(urlObj) {
  return (
    urlObj.origin === window.location.origin &&
    urlObj.pathname.startsWith("/api/")
  );
}

function patchFetch() {
  realFetchRef = window.fetch.bind(window);
  const realFetch = realFetchRef;

  window.fetch = async function mockFetch(input, init) {
    let urlObj;
    try {
      const raw = input instanceof Request ? input.url : input;
      urlObj = new URL(raw, window.location.href);
    } catch {
      return realFetch(input, init);
    }

    if (!isMockApiUrl(urlObj)) return realFetch(input, init);

    const method = (
      init?.method ||
      (input instanceof Request ? input.method : "GET") ||
      "GET"
    ).toUpperCase();
    const body = await extractBody(input, init);

    try {
      const result = await routeApi(method, urlObj, body);
      return jsonResponse(result);
    } catch (err) {
      if (err instanceof MockApiError)
        return jsonResponse({ detail: err.detail }, err.status);
      console.error(
        "[mockAdapter] unexpected error handling",
        method,
        urlObj.pathname,
        err,
      );
      return jsonResponse({ detail: String(err?.message ?? err) }, 500);
    }
  };
}

