/**
 * Static-site mock adapter — lets the whole redesigned bench run as a fully
 * static site (GitHub Pages, `npx http-server dist`, ...) with **no Python
 * backend at all**.
 *
 * Activated only when `import.meta.env.VITE_MOCK === "1"` (see
 * `npm run build:mock` in package.json). Installed from `index.jsx` before
 * React renders, as a single guarded top-level import:
 *
 *   if (import.meta.env.VITE_MOCK === "1") { await import("./api/mockAdapter.js"); }
 *
 * It does two things:
 *
 * 1. Patches `window.fetch` to intercept same-origin `/api/*` requests and
 *    answer them from an in-memory store seeded from the JSON fixtures under
 *    `frontend/public/mock/` (generated by `scripts/generate_mock_fixtures.py`
 *    from `artiq_http/mock_backend.py` — see that script's docstring for the
 *    fixture-to-endpoint mapping and the `<slug>` filename encoding used by
 *    `arginfo/<slug>.json`). Every other request (including the fixture JSON
 *    itself) is passed through to the real `fetch`.
 * 2. Replaces `window.EventSource` with a shim that recognises
 *    `/api/datasets/stream/<prefix>` URLs and replays + animates the mock
 *    dataset state on a timer, reproducing sse.py's event protocol exactly
 *    (`init`/`update`/`delete`/`heartbeat`/`error`, `event.data` as a JSON
 *    string). Any other URL still gets a real `EventSource`.
 *
 * No new npm dependencies — everything here is hand-rolled against standard
 * browser APIs (fetch, Response, URL, EventTarget, MessageEvent).
 *
 * Fidelity notes:
 *  - A submitted run's lifecycle mirrors `mock_backend.py` exactly: it's
 *    inserted `pending`, flips to `running` after `SUBMIT_PENDING_DELAY_MS`
 *    and (for ndscan submissions) starts streaming points derived from the
 *    axes actually submitted, then completes and leaves the schedule once
 *    every point is in. A submission with no scan axes completes immediately
 *    as a single-point run (real ndscan 0D runs measure once and complete —
 *    see `beginZeroAxisRun`); a plain (non-ndscan) submission has no live
 *    data to stream, so it's just removed from the schedule after a short
 *    simulated run time. See IMPL-SPEC.md #17 / the mock-fidelity fix that
 *    added this — the whole point of this package is "the demo is clickable
 *    end to end".
 *  - The seeded `ndscan.rid_4823` (live) / `ndscan.rid_4821` (ghost) / `.rid_1`
 *    animations are ported line-for-line from `mock_backend.py`'s
 *    `_update_loop`: both are RabiFlop (`rabi.pulse_duration`, 101 points),
 *    matching the identity of the schedule item RID 4823 actually declares —
 *    fragment FQN, scanned axis and channel names all agree.
 *  - A freshly *submitted* scan (from this adapter, not seeded) is generic:
 *    it samples a synthetic Lorentzian bump over the actual axis/axes the
 *    user picked (1 or 2 supported, matching the session model's "max 2
 *    axes" rule) rather than trying to simulate real physics, and completes
 *    (and leaves the schedule) once its declared point total is reached, the
 *    same lifecycle a real run has.
 */

