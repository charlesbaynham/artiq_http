function extractNdscanDefault(arginfo) {
  const ndscanParams = arginfo?.ndscan_params;
  if (!ndscanParams || !Array.isArray(ndscanParams)) return {};
  try {
    const spec = ndscanParams[0];
    if (!spec || typeof spec !== "object") return {};
    const defaultJson = spec.default;
    if (typeof defaultJson !== "string") return {};
    const parsed = JSON.parse(defaultJson);
    return parsed && typeof parsed === "object" ? parsed : {};
  } catch {
    return {};
  }
}

function extractSchemataFromArginfo(arginfo) {
  const s = extractNdscanDefault(arginfo).schemata;
  return s && typeof s === "object" ? s : {};
}

function extractInstancesFromArginfo(arginfo) {
  const i = extractNdscanDefault(arginfo).instances;
  return i && typeof i === "object" ? i : {};
}

function invertInstances(instances) {
  const map = {};
  for (const [path, fqns] of Object.entries(instances || {})) {
    if (!Array.isArray(fqns)) continue;
    for (const fqn of fqns) {
      const list = map[fqn] || (map[fqn] = []);
      if (!list.includes(path)) list.push(path);
    }
  }
  return map;
}

function resolvePath(fqn, explicitPath, fqnToPaths) {
  const candidates = fqnToPaths[fqn];
  if (explicitPath != null) {
    if (candidates && !candidates.includes(explicitPath)) {
      throw new MockApiError(
        422,
        `explicit path '${explicitPath}' for '${fqn}' is not one of its instance paths ${JSON.stringify(
          candidates,
        )}`,
      );
    }
    return explicitPath;
  }
  if (!candidates || candidates.length === 0) return "";
  if (candidates.length === 1) return candidates[0];
  throw new MockApiError(
    422,
    `parameter '${fqn}' exists at multiple instance paths ${JSON.stringify(
      candidates,
    )}; specify the path explicitly to disambiguate`,
  );
}

function splitFixedParam(value) {
  if (
    value &&
    typeof value === "object" &&
    !Array.isArray(value) &&
    "value" in value
  ) {
    return [value.value, value.path ?? null];
  }
  return [value, null];
}

const SUPPORTED_GENERATORS = {
  linear: ["start", "stop", "num_points"],
  centre_span: ["centre", "half_span", "num_points"],
  list: ["values"],
};

function buildAxis(axis, fqnToPaths) {
  const fqn = axis?.fqn;
  if (!fqn || typeof fqn !== "string")
    throw new MockApiError(422, "scan axis missing 'fqn'");
  const gtype = axis.type;
  if (!(gtype in SUPPORTED_GENERATORS)) {
    throw new MockApiError(
      422,
      `invalid scan type '${gtype}'. Must be one of: ${Object.keys(
        SUPPORTED_GENERATORS,
      )
        .sort()
        .join(", ")}`,
    );
  }
  const rangeIn = axis.range;
  if (!rangeIn || typeof rangeIn !== "object") {
    throw new MockApiError(
      422,
      `scan axis '${fqn}' missing or invalid 'range'`,
    );
  }
  const required = SUPPORTED_GENERATORS[gtype];
  const missing = required.filter((k) => !(k in rangeIn));
  if (missing.length) {
    throw new MockApiError(
      422,
      `scan axis '${fqn}' (${gtype}) range missing keys: ${missing.join(", ")}`,
    );
  }
  const rangeOut = { ...rangeIn };
  if (rangeOut.randomise_order === undefined) rangeOut.randomise_order = false;
  const path = resolvePath(fqn, axis.path ?? null, fqnToPaths);
  return { type: gtype, range: rangeOut, fqn, path };
}

function buildNdscanParamsFromArginfo(
  arginfo,
  file,
  className,
  axes,
  fixedParams,
  numRepeats,
) {
  const schemata = extractSchemataFromArginfo(arginfo);
  if (!schemata || Object.keys(schemata).length === 0) {
    throw new MockApiError(
      422,
      `Experiment ${file}/${className} has no ndscan schemata`,
    );
  }
  const fqnToPaths = invertInstances(extractInstancesFromArginfo(arginfo));

  const overrides = {};
  for (const [fqn, raw] of Object.entries(fixedParams || {})) {
    const [value, explicitPath] = splitFixedParam(raw);
    const path = resolvePath(fqn, explicitPath, fqnToPaths);
    overrides[fqn] = [{ path, value }];
  }

  const paramsData = {
    overrides,
    scan: {
      axes: (axes || []).map((ax) => buildAxis(ax, fqnToPaths)),
      num_repeats: numRepeats,
      no_axes_mode: "single",
      randomise_order_globally: false,
    },
  };
  return JSON.stringify(paramsData);
}

function getNdscanJson(argumentsObj) {
  const v = argumentsObj?.ndscan_params;
  if (v == null) return [null, null];
  if (typeof v === "string") return [v, null];
  if (Array.isArray(v) && v.length) {
    const spec = v[0];
    if (spec && typeof spec === "object" && typeof spec.default === "string")
      return [spec.default, null];
  }
  return [
    null,
    "ndscan_params must be a PYON/JSON string (or [spec, None, None] triple)",
  ];
}

const VALID_SCAN_TYPES = new Set(["linear", "centre_span", "list"]);
const RANGE_KEYS = {
  linear: ["start", "stop", "num_points"],
  centre_span: ["centre", "half_span", "num_points"],
  list: ["values"],
};

function validateAxis(axis, canonicalFqns, idx) {
  if (!axis || typeof axis !== "object")
    return `scan.axes[${idx}] is not a dict`;
  const fqn = axis.fqn;
  if (!fqn || typeof fqn !== "string")
    return `scan.axes[${idx}]: missing or invalid 'fqn'`;
  if (canonicalFqns.size && !canonicalFqns.has(fqn))
    return `scan.axes[${idx}]: unknown parameter '${fqn}'`;
  if (!("path" in axis)) return `scan.axes[${idx}]: missing 'path'`;
  const scanType = axis.type;
  if (!scanType || !VALID_SCAN_TYPES.has(scanType)) {
    return `scan.axes[${idx}]: invalid scan type '${scanType}'. Must be one of: ${[
      ...VALID_SCAN_TYPES,
    ]
      .sort()
      .join(", ")}`;
  }
  const rangeData = axis.range;
  if (!rangeData || typeof rangeData !== "object")
    return `scan.axes[${idx}]: missing or invalid 'range'`;
  const missing = RANGE_KEYS[scanType].filter((k) => !(k in rangeData));
  if (missing.length)
    return `scan.axes[${idx}]: range missing ${missing.join(", ")}`;

  if (scanType === "list") {
    const values = rangeData.values;
    if (!Array.isArray(values) || values.length === 0) {
      return `scan.axes[${idx}]: list scan requires a non-empty 'values' list`;
    }
    return null;
  }

  const numericKeys = RANGE_KEYS[scanType].slice(0, -1);
  for (const k of numericKeys) {
    if (!Number.isFinite(Number(rangeData[k])))
      return `scan.axes[${idx}]: range values must be numeric`;
  }
  const numPoints = Number(rangeData.num_points);
  if (!Number.isInteger(numPoints))
    return `scan.axes[${idx}]: range values must be numeric`;
  if (numPoints <= 0)
    return `scan.axes[${idx}]: num_points (${numPoints}) must be greater than 0`;
  if (scanType === "linear" && numPoints < 2)
    return `scan.axes[${idx}]: linear scan needs num_points >= 2`;
  if (
    scanType === "linear" &&
    Number(rangeData.start) === Number(rangeData.stop)
  ) {
    return `scan.axes[${idx}]: linear scan start and stop must differ`;
  }
  return null;
}

function validateOverrides(overrides) {
  if (!overrides || typeof overrides !== "object" || Array.isArray(overrides)) {
    return "ndscan_params 'overrides' must be a dict";
  }
  for (const [fqn, specs] of Object.entries(overrides)) {
    if (!Array.isArray(specs) || specs.length === 0) {
      return `override for '${fqn}' must be a non-empty list of path/value specs`;
    }
    for (const spec of specs) {
      if (
        !spec ||
        typeof spec !== "object" ||
        !("path" in spec) ||
        !("value" in spec)
      ) {
        return `override for '${fqn}' must contain dicts with 'path' and 'value'`;
      }
    }
  }
  return null;
}

/** Port of ndscan_validation.validate_ndscan_params. Returns an error string or null. */
function validateNdscanParamsArguments(argumentsObj, arginfo) {
  const [jsonString, err] = getNdscanJson(argumentsObj);
  if (err) return err;
  if (jsonString == null) return null;

  let paramsData;
  try {
    paramsData = JSON.parse(jsonString);
  } catch (e) {
    return `ndscan_params JSON parse error: ${e.message}`;
  }
  if (!paramsData || typeof paramsData !== "object")
    return "ndscan_params JSON must parse to a dict";
  if (!("scan" in paramsData))
    return "ndscan_params missing required key 'scan'";
  const scan = paramsData.scan;
  if (!scan || typeof scan !== "object")
    return "ndscan_params 'scan' must be a dict";
  const axes = scan.axes ?? [];
  if (!Array.isArray(axes)) return "ndscan_params 'scan.axes' must be a list";

  let canonicalFqns = new Set();
  if (arginfo != null)
    canonicalFqns = new Set(Object.keys(extractSchemataFromArginfo(arginfo)));

  const scannedFqns = new Set();
  for (let idx = 0; idx < axes.length; idx++) {
    const e = validateAxis(axes[idx], canonicalFqns, idx);
    if (e) return e;
    scannedFqns.add(axes[idx].fqn);
  }

  const overrides = paramsData.overrides ?? {};
  const errO = validateOverrides(overrides);
  if (errO) return errO;
  for (const fqn of Object.keys(overrides)) {
    if (canonicalFqns.size && !canonicalFqns.has(fqn))
      return `override references unknown parameter '${fqn}'`;
    if (scannedFqns.has(fqn))
      return `parameter '${fqn}' is both scanned and fixed (in overrides)`;
  }

  const numRepeats = scan.num_repeats ?? 1;
  if (!Number.isInteger(numRepeats) || numRepeats < 1) {
    return `scan.num_repeats (${numRepeats}) must be an integer >= 1`;
  }
  return null;
}

// ── extract_arginfo_defaults / _filter_ndscan_always_shown ports (notifiers.py) ──

function parseNdscanDefaultValue(typeStr, defaultStr) {
  if (typeStr === "bool") return String(defaultStr).toLowerCase() === "true";
  if (typeStr === "float") return parseFloat(defaultStr);
  if (typeStr === "int") {
    const n = parseInt(defaultStr, 10);
    return Number.isNaN(n) ? parseFloat(defaultStr) : n;
  }
  return defaultStr;
}

function extractNdscanDefaults(arginfo) {
  const schemata = extractSchemataFromArginfo(arginfo);
  const defaults = {};
  for (const [fqn, schema] of Object.entries(schemata)) {
    if (!schema || typeof schema !== "object") continue;
    const paramName = fqn.split(".").pop();
    const defaultValue = schema.default;
    if (defaultValue != null) {
      defaults[paramName] = parseNdscanDefaultValue(
        schema.type ?? "str",
        defaultValue,
      );
    }
  }
  return defaults;
}

function extractArginfoDefaults(arginfo) {
  const defaults = {};
  if (arginfo && "ndscan_params" in arginfo) {
    Object.assign(defaults, extractNdscanDefaults(arginfo));
  }
  for (const [argName, argData] of Object.entries(arginfo || {})) {
    if (!Array.isArray(argData) || argData.length < 2) continue;
    const [typeStr, specDict] = argData;
    if (!specDict || typeof specDict !== "object") continue;
    if (
      [
        "NumberValue",
        "StringValue",
        "BooleanValue",
        "EnumerationValue",
        "Scannable",
      ].includes(typeStr)
    ) {
      if ("default" in specDict) defaults[argName] = specDict.default;
    }
  }
  return defaults;
}

function filterNdscanAlwaysShown(arginfo) {
  if (!arginfo || !("ndscan_params" in arginfo)) return arginfo;
  const ndscanParams = arginfo.ndscan_params;
  if (!ndscanParams || !Array.isArray(ndscanParams)) return arginfo;
  try {
    const spec = ndscanParams[0];
    if (!spec || typeof spec !== "object") return arginfo;
    const defaultJson = spec.default;
    if (typeof defaultJson !== "string") return arginfo;
    const paramsData = JSON.parse(defaultJson);
    const alwaysShown = paramsData.always_shown ?? [];

    const alwaysShownFqns = new Set();
    for (const item of alwaysShown) {
      if (item && typeof item === "object" && "__jsonclass__" in item) {
        const jc = item.__jsonclass__;
        if (Array.isArray(jc) && jc.length === 2) {
          const tupleData = jc[1];
          if (Array.isArray(tupleData) && tupleData.length > 0) {
            const inner = tupleData[0];
            if (Array.isArray(inner) && inner.length > 0)
              alwaysShownFqns.add(inner[0]);
          }
        }
      } else if (Array.isArray(item) && item.length > 0) {
        alwaysShownFqns.add(item[0]);
      }
    }

    if (alwaysShownFqns.size === 0) {
      const result = { ...arginfo };
      delete result.ndscan_params;
      return result;
    }

    const schemata = paramsData.schemata ?? {};
    paramsData.schemata = Object.fromEntries(
      Object.entries(schemata).filter(([fqn]) => alwaysShownFqns.has(fqn)),
    );

    const instances = paramsData.instances ?? {};
    const filteredInstances = {};
    for (const [key, fqns] of Object.entries(instances)) {
      const kept = (fqns || []).filter((fqn) => alwaysShownFqns.has(fqn));
      if (kept.length) filteredInstances[key] = kept;
    }
    paramsData.instances = filteredInstances;

    return {
      ...arginfo,
      ndscan_params: [
        { ty: spec.ty ?? "PYONValue", default: JSON.stringify(paramsData) },
        null,
        null,
      ],
    };
  } catch {
    return arginfo;
  }
}

// ── Explist / arginfo / defaults / recompute handlers ────────────────────────

function parseFields(fieldsParam) {
  return (fieldsParam ?? "name,file,class_name,docstring")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
}

function projectEntry(exp, fields, full) {
  const wanted = new Set(fields);
  const out = {
    name: exp.name,
    file: exp.file,
    class_name: exp.class_name,
    arginfo: wanted.has("arginfo") ? (exp.arginfo ?? null) : null,
    argument_ui: wanted.has("argument_ui") ? (exp.argument_ui ?? null) : null,
    scheduler_defaults: wanted.has("scheduler_defaults")
      ? (exp.scheduler_defaults ?? null)
      : null,
    docstring: wanted.has("docstring") ? (exp.docstring ?? null) : null,
  };
  if (out.arginfo && !full) out.arginfo = filterNdscanAlwaysShown(out.arginfo);
  return out;
}

function handleGetExplist(url) {
  const fields = parseFields(url.searchParams.get("fields"));
  const full = url.searchParams.get("full") === "true";
  return {
    current_rev: state.explist.current_rev,
    scanning: state.explist.scanning,
    experiments: state.explist.experiments.map((e) =>
      projectEntry(e, fields, full),
    ),
    default_revision_fallback: state.explist.default_revision_fallback,
  };
}

function handleSearchExplist(url) {
  const q = url.searchParams.get("q") ?? "";
  const fields = parseFields(url.searchParams.get("fields"));
  const full = url.searchParams.get("full") === "true";
  let exps = state.explist.experiments;
  if (q) {
    const ql = q.toLowerCase();
    exps = exps.filter(
      (e) =>
        e.name.toLowerCase().includes(ql) ||
        e.file.toLowerCase().includes(ql) ||
        e.class_name.toLowerCase().includes(ql),
    );
  }
  return {
    current_rev: state.explist.current_rev,
    scanning: state.explist.scanning,
    experiments: exps.map((e) => projectEntry(e, fields, full)),
    default_revision_fallback: state.explist.default_revision_fallback,
  };
}

