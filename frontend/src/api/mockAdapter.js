class MockApiError extends Error {
  constructor(status, detail) {
    super(typeof detail === "string" ? detail : JSON.stringify(detail));
    this.status = status;
    this.detail = detail;
  }
}

function jsonResponse(data, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: { "Content-Type": "application/json" },
  });
}

function gauss(mean, sigma) {
  let u = 0;
  let v = 0;
  while (u === 0) u = Math.random();
  while (v === 0) v = Math.random();
  const z = Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
  return mean + z * sigma;
}

function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function clampByte(v) {
  return Math.max(0, Math.min(255, Math.round(v)));
}

function linspace(start, stop, n) {
  if (n <= 1) return [start];
  const out = [];
  for (let i = 0; i < n; i++) out.push(start + ((stop - start) * i) / (n - 1));
  return out;
}

/**
 * Filesystem-safe encoding of `<file>:<class_name>` used for arginfo fixture
 * filenames (`frontend/public/mock/arginfo/<slug>.json`).
 *
 * MUST exactly match `slugify()` in `scripts/generate_mock_fixtures.py` —
 * both sides need to resolve the same experiment to the same fixture file.
 */
function slugify(file, className) {
  const safeFile = file.replaceAll("/", "_").replaceAll("\\", "_");
  return `${safeFile}__${className}`;
}

