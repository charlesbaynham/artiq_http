// site, mirroring frontend/public/mock/ at dev time.
const MOCK_BASE = `${import.meta.env.BASE_URL}mock/`;

let realFetchRef = null;

async function fetchFixture(name) {
  const fetcher = realFetchRef || window.fetch;
  const res = await fetcher(MOCK_BASE + name);
  if (!res.ok) {
    throw new Error(
      `mockAdapter: failed to load fixture ${name}: ${res.status} ${res.statusText}`,
    );
  }
  return res.json();
}

let loadPromise = null;

function ensureLoaded() {
  if (loadPromise) return loadPromise;
  loadPromise = (async () => {
    const [explist, schedule, datasets, health, logs] = await Promise.all([
      fetchFixture("explist.json"),
      fetchFixture("schedule.json"),
      fetchFixture("datasets.json"),
      fetchFixture("health.json"),
      fetchFixture("logs.json"),
    ]);
    state.explist = explist;
    state.schedule = schedule;
    state.datasets = datasets;
    state.health = health;
    state.logs = logs.logs || [];
    state.nextRid = 4825;
  })();
  return loadPromise;
}

async function loadArginfoFixture(file, className) {
  const slug = slugify(file, className);
  if (argInfoCache.has(slug)) return argInfoCache.get(slug);
  try {
    const doc = await fetchFixture(`arginfo/${slug}.json`);
    argInfoCache.set(slug, doc);
    return doc;
  } catch (err) {
    console.warn("[mockAdapter] could not load arginfo fixture", slug, err);
    return null;
  }
}

