function installMockAdapter() {
  if (window.__artiqHttpMockInstalled) return;
  window.__artiqHttpMockInstalled = true;

  patchFetch();
  patchEventSource();
  mountDemoBanner();

  if (typeof document !== "undefined") {
    if (!document.hidden) startTicking();
    document.addEventListener("visibilitychange", () => {
      if (document.hidden) stopTicking();
      else startTicking();
    });
  } else {
    startTicking();
  }

  // Warm the fixture load immediately rather than waiting for the first API
  // call, so the app's first render doesn't pay the extra round trip.
  ensureLoaded().catch((err) =>
    console.error("[mockAdapter] failed to load fixtures", err),
  );
}

if (import.meta.env.VITE_MOCK === "1") {
  installMockAdapter();
}
